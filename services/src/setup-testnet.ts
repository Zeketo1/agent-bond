// One-shot testnet setup. Run once:  npm run setup:testnet
//   1. generates keys for contract, guardian, sponsor, agent, vendor, attacker (kept locally)
//   2. creates and funds those accounts through the public testnet faucet (free test NEAR)
//   3. deploys contract/target/.../agent_bond.wasm and initializes it with the guardian
//   4. the sponsor registers the agent with a bond, a budget and a spending policy
//   5. writes everything to services/.env (git-ignored). Private keys are never printed.
//
// Testnet only. It refuses to run if .env already exists.

import { Account, JsonRpcProvider, KeyPair, teraToGas } from "near-api-js";
import type { KeyPairString } from "near-api-js";
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { BOND, BUDGET, demoPolicy } from "./demo-config.js";
import { nearToYocto } from "./types.js";

const ENV_PATH = new URL("../.env", import.meta.url);
const WASM_PATH = new URL("../../contract/target/wasm32-unknown-unknown/release/agent_bond.wasm", import.meta.url);
const RPC = process.env.NEAR_RPC_URL ?? "https://test.rpc.fastnear.com";
const FAUCETS = ["https://helper.nearprotocol.com/account", "https://helper.testnet.near.org/account"];

if (existsSync(ENV_PATH)) {
  console.error(".env already exists. Delete it first if you really want a fresh setup (old accounts are kept on-chain).");
  process.exit(1);
}
if (!existsSync(WASM_PATH)) {
  console.error("Contract wasm not found. Build it first: cd contract && cargo build --target wasm32-unknown-unknown --release");
  process.exit(1);
}

const provider = new JsonRpcProvider({ url: RPC });
const suffix = randomBytes(3).toString("hex");
const roles = ["bond", "guard", "spons", "agent", "vendor", "evil"] as const;
type Role = (typeof roles)[number];
const id = (r: Role) => `${r}-${suffix}.testnet`;
const keys = Object.fromEntries(roles.map((r) => [r, KeyPair.fromRandom("ed25519")])) as Record<Role, KeyPair>;

async function fund(role: Role) {
  const body = JSON.stringify({ newAccountId: id(role), newAccountPublicKey: keys[role].getPublicKey().toString() });
  let last = "";
  for (const url of FAUCETS) {
    try {
      const res = await fetch(url, { method: "POST", headers: { "content-type": "application/json" }, body });
      if (res.ok) return;
      last = `${url} -> HTTP ${res.status} ${(await res.text()).slice(0, 200)}`;
    } catch (e) {
      last = `${url} -> ${(e as Error).message}`;
    }
  }
  throw new Error(`faucet failed for ${id(role)}: ${last}`);
}

async function waitForAccount(role: Role) {
  const acct = new Account(id(role), provider, keys[role].toString() as KeyPairString);
  for (let i = 0; i < 20; i++) {
    try {
      return { acct, balance: await acct.getBalance() };
    } catch {
      await new Promise((r) => setTimeout(r, 1500));
    }
  }
  throw new Error(`account ${id(role)} never appeared on chain`);
}

console.log(`creating accounts with suffix -${suffix} on testnet...`);
for (const r of roles) {
  await fund(r);
  const { balance } = await waitForAccount(r);
  console.log(`  ${id(r)} funded (${(Number(balance / 10n ** 21n) / 1000).toFixed(2)} NEAR)`);
}

const acct = (r: Role) => new Account(id(r), provider, keys[r].toString() as KeyPairString);

console.log("deploying contract...");
await acct("bond").deployContract(new Uint8Array(readFileSync(WASM_PATH)));
await acct("bond").callFunction({
  contractId: id("bond"),
  methodName: "new",
  args: { guardian: id("guard") },
  gas: teraToGas("30"),
  deposit: 0n,
});

console.log("sponsor registers the agent with a bond and a budget...");
await acct("spons").callFunction({
  contractId: id("bond"),
  methodName: "register_agent",
  args: { agent_id: id("agent"), bond: nearToYocto(BOND).toString(), policy: demoPolicy() },
  gas: teraToGas("30"),
  deposit: nearToYocto(String(Number(BOND) + Number(BUDGET))),
});

const env = `# Generated by setup-testnet. Testnet only. Never commit this file.
NEAR_RPC_URL=${RPC}
BOND_CONTRACT=${id("bond")}

GUARDIAN_ACCOUNT=${id("guard")}
GUARDIAN_KEY=${keys.guard.toString()}
SPONSOR_ACCOUNT=${id("spons")}
SPONSOR_KEY=${keys.spons.toString()}
AGENT_ACCOUNT=${id("agent")}
AGENT_KEY=${keys.agent.toString()}

TRUSTED_RECIPIENTS=${id("vendor")}
VENDOR_ACCOUNT=${id("vendor")}
ATTACKER_ACCOUNT=${id("evil")}

# Demo amounts (NEAR) used by the agent scenarios
HONEST_AMOUNT=0.5
ATTACK_AMOUNT=0.8

# Optional: private AI review via NEAR AI Cloud
NEAR_AI_API_KEY=
`;
writeFileSync(ENV_PATH, env, { mode: 0o600 });

console.log(`
Done. Contract: ${id("bond")}
  explorer: https://testnet.nearblocks.io/address/${id("bond")}
Next:
  npm run guardian          (terminal 1)
  npm run agent:honest      (terminal 2)
  npm run agent:injected    (terminal 2)
`);
